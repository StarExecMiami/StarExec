#!/usr/bin/env python3
"""Generate css/global/_icon-data.scss from the vendored Lucide SVGs.

Each icon becomes a CSS data URI in the Sass map $icon-data. Icons are used
as masks, so only their shape matters; the colour comes from CSS.

Run from the repository root:  python3 scripts/build-icon-data.py
Pass --check to fail (exit 1) when the committed file is out of date.
"""

import re
import sys
from pathlib import Path
from urllib.parse import quote

ROOT = Path(__file__).resolve().parent.parent
ICON_DIR = ROOT / "starexec-app/src/main/icons/lucide"
OUTPUT = ROOT / "starexec-app/src/main/webapp/css/global/_icon-data.scss"

HEADER = """\
// GENERATED by scripts/build-icon-data.py from starexec-app/src/main/icons/lucide.
// Do not edit by hand.

// The ISC licence asks for this notice in copies; /*! survives compressed Sass.
/*! Lucide icons (lucide-static), ISC License, Copyright (c) 2026 Lucide Icons
 * and Contributors. Full text: starexec-app/src/main/icons/lucide/LICENSE */

"""

FOOTER = """
// Returns the data URI of a vendored icon; fails the build on an unknown name.
@function icon($name) {
	@if not map-has-key($icon-data, $name) {
		@error "Unknown icon '#{$name}'. Add it to starexec-app/src/main/icons/lucide and rerun scripts/build-icon-data.py.";
	}

	@return map-get($icon-data, $name);
}
"""


def minify(svg: str) -> str:
    svg = re.sub(r"<!--.*?-->", "", svg, flags=re.S)
    svg = re.sub(r'\s+class="[^"]*"', "", svg)
    # A mask only reads alpha; a fixed colour avoids depending on currentColor.
    svg = svg.replace("currentColor", "#000")
    svg = re.sub(r"\s+", " ", svg).strip()
    svg = re.sub(r"\s*(/?>)\s*", r"\1", svg)
    svg = re.sub(r">\s+<", "><", svg)
    return svg.replace('"', "'")


def data_uri(svg: str) -> str:
    # Percent-encode only what CSS url("...") and data URIs require.
    return "data:image/svg+xml," + quote(svg, safe=" '/=:;,.-_()!*~")


def render() -> str:
    icons = sorted(ICON_DIR.glob("*.svg"))
    if not icons:
        sys.exit(f"no icons found in {ICON_DIR}")
    lines = [f'\t"{p.stem}": url("{data_uri(minify(p.read_text()))}"),' for p in icons]
    return HEADER + "$icon-data: (\n" + "\n".join(lines) + "\n);\n" + FOOTER


def main() -> int:
    args = sys.argv[1:]
    if args not in ([], ["--check"]):
        print(f"usage: {sys.argv[0]} [--check]", file=sys.stderr)
        return 2
    content = render()
    if args == ["--check"]:
        current = OUTPUT.read_text() if OUTPUT.exists() else ""
        if current != content:
            print(
                f"{OUTPUT.relative_to(ROOT)} is out of date; run scripts/build-icon-data.py"
            )
            return 1
        return 0
    OUTPUT.write_text(content)
    print(f"wrote {OUTPUT.relative_to(ROOT)} ({content.count('url(')} icons)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
